import type { CSSProperties } from "react";
import type { LucideIcon } from "lucide-react";
import FaIcon from "./FaIcon";

export type { LucideIcon };

type Props = { size?: number | string; className?: string; color?: string; fill?: string; title?: string; style?: CSSProperties; strokeWidth?: number; "aria-label"?: string; "aria-hidden"?: boolean };

/** Use the server's bundled Font Awesome glyphs for application controls as well as entity icons. */
function icon(className: string, filledClassName?: string): LucideIcon {
  const Component = ({ size = 16, className: extra = "", color, fill, title, style, "aria-label": ariaLabel }: Props) => {
    const iconClass = fill && fill !== "none" && filledClassName ? filledClassName : className;
    return <FaIcon className={`${iconClass} ${extra}`} size={Number(size) || 16} title={title || ariaLabel} style={{ color, ...style }} />;
  };
  return Component as LucideIcon;
}

